function getImages(folder: string, count: number, prefix: string = ''): string[] {
  const imgs: string[] = [];
  if (prefix) {
    for (let i = 1; i <= count; i++) imgs.push(`/images/${folder}/${prefix}-${i}.jpg`);
  } else {
    for (let i = 1; i <= count; i++) imgs.push(`/images/${folder}/${i}.jpg`);
  }
  return imgs;
}

